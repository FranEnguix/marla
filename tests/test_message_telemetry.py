    assert summary["consultation_response_count"] == 1
    assert summary["retry_count"] == 1
    assert summary["lifecycle_message_count"] == 1
    assert summary["sent_count_by_type"]["ADVISORY_REQUEST"] == 1
    assert summary["message_count_by_type"]["ADVISORY_REQUEST"] == 1  # kept as an alias of sent_count_by_type


