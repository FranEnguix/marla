def test_sent_addressed_and_handled_counts_derive_from_the_same_event_stream():
    """The canonical counting rule: sent-by/addressed-to are two groupings
    of the SENT events, handled-by is a grouping of the HANDLED events --
    all derived from one event list, so they can never drift apart or
    double-count."""
    log = telemetry.start_run("test-run")
    build_message("gatekeeper@localhost", _metadata(sender="rl_orchestrator", receiver="gatekeeper"))
    build_message("plan-maker@localhost", _metadata(sender="rl_orchestrator", receiver="plan_maker_1"))
    sent_3 = build_message("rl-orchestrator@localhost", _metadata(sender="gatekeeper", receiver="rl_orchestrator"))
    event3 = log.events[2]
    telemetry.record_handled_if_active(
        message_id=event3.message_id, sender_alias=event3.sender_alias, receiver_alias=event3.receiver_alias,
        performative=event3.performative, message_type=event3.message_type,
        conversation_id=event3.conversation_id, request_id=event3.request_id,
    )
    del sent_3  # only used to build the message

    summary = log.summarize()
    assert summary["sent_count_by_agent"]["rl_orchestrator"] == 2
    assert summary["sent_count_by_agent"]["gatekeeper"] == 1
    assert summary["addressed_count_by_agent"]["gatekeeper"] == 1
    assert summary["addressed_count_by_agent"]["plan_maker_1"] == 1
    assert summary["addressed_count_by_agent"]["rl_orchestrator"] == 1
    assert summary["handled_count_by_agent"] == {"rl_orchestrator": 1}
    assert summary["total_message_count"] == 3
    assert summary["total_event_count"] == 4  # 3 sent + 1 handled
    assert "received_count_by_agent" not in summary  # deprecated ambiguous name, never retained
    # Every SENT message counted exactly once in aggregate too.
    assert sum(summary["sent_count_by_agent"].values()) == 3
    assert sum(summary["addressed_count_by_agent"].values()) == 3


def test_sent_not_handled_count_makes_an_unmatched_message_visible():
    """A message with no matching behaviour (MARLA has observed real
    "No behaviour matched for message ..." cases) is sent but never
    handled -- this must be a visible discrepancy, not silently absorbed
    into a count that looks the same either way (invariant D)."""
    log = telemetry.start_run("test-run")
    build_message("gatekeeper@localhost", _metadata(message_type=MessageType.START_EXPERIMENT))  # never handled
    handled_msg = build_message("plan-maker@localhost", _metadata(message_type=MessageType.READY_CHECK))
    del handled_msg
    handled_event = log.events[1]
    telemetry.record_handled_if_active(
        message_id=handled_event.message_id, sender_alias=handled_event.sender_alias,
        receiver_alias=handled_event.receiver_alias, performative=handled_event.performative,
        message_type=handled_event.message_type, conversation_id=handled_event.conversation_id,
        request_id=handled_event.request_id,
    )

    summary = log.summarize()
    assert summary["sent_not_handled_count"] == 1


def test_handled_event_never_double_counted_against_sent():
    """Recording a message's sent and handled events must not let either
    inflate the other's total (invariant C)."""
    log = telemetry.start_run("test-run")
    build_message("gatekeeper@localhost", _metadata())
    sent = log.events[0]
    telemetry.record_handled_if_active(
        message_id=sent.message_id, sender_alias=sent.sender_alias, receiver_alias=sent.receiver_alias,
        performative=sent.performative, message_type=sent.message_type,
        conversation_id=sent.conversation_id, request_id=sent.request_id,
    )
    summary = log.summarize()
    assert summary["total_message_count"] == 1
    assert summary["sent_count_by_agent"]["rl_orchestrator"] == 1
    assert summary["handled_count_by_agent"]["gatekeeper"] == 1
    assert summary["sent_not_handled_count"] == 0


