class ScenarioFigureError(RuntimeError):
    """A batch cannot proceed (bad input, would overwrite files, ...)."""


def sanitize_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._-]+", "_", name).strip("._")
    return cleaned or "scenario"


def figure_stem(file_name: str, effective_seed: int | None, view: View) -> str:
    """``None`` for a scenario definition (no ``_seed_``)."""
    stem = file_name if effective_seed is None else f"{file_name}_seed_{effective_seed}"
    return stem + ("_verbose" if view == "verbose" else "")


def figure_files(file_name: str, effective_seed: int | None, views: Iterable[View], formats: Iterable[str]) -> dict[str, dict[str, str]]:
    return {view: {fmt: f"{figure_stem(file_name, effective_seed, view)}.{fmt}" for fmt in formats} for view in views}


def parse_seed_list(text: str) -> list[int]:
    """``"11,12,20-22"`` -> ``[11, 12, 20, 21, 22]`` (inclusive ranges)."""
    seeds: list[int] = []
    for part in (p.strip() for p in text.split(",")):
        if not part:
            continue
        match = re.fullmatch(r"(\d+)\s*-\s*(\d+)", part)
        if match:
            lo, hi = int(match.group(1)), int(match.group(2))
            if hi < lo:
                raise ValueError(f"empty seed range {part!r}")
            seeds.extend(range(lo, hi + 1))
        elif re.fullmatch(r"\d+", part):
            seeds.append(int(part))
        else:
            raise ValueError(f"not a seed or seed range: {part!r}")
    if not seeds:
        raise ValueError("no seeds given")
    return [validate_scenario_seed(s) for s in seeds]


def parse_formats(text: str) -> tuple[str, ...]:
    """``"all"`` or a comma-separated subset of :data:`FORMATS`."""
    if text.strip().lower() == "all":
        return FORMATS
    formats = tuple(dict.fromkeys(f.strip().lower().lstrip(".") for f in text.split(",") if f.strip()))
    unknown = [f for f in formats if f not in FORMATS]
    if not formats or unknown:
        raise ValueError(f"unsupported format(s) {unknown or text!r}; choose from {', '.join(FORMATS)}")
    return formats


def _package_version(name: str) -> str | None:
    try:
        return version(name)
    except PackageNotFoundError:
        return None


# --------------------------------------------------------------------- inputs


@dataclass
class SeedRecord:
    """Everything the inputs say about one (scenario, requested seed)."""

    requested_seed: int
    sources: set[str] = field(default_factory=set)
    census_hosts: dict[str, tuple[str, str, bool]] | None = None
    episode_target_counts: set[int] = field(default_factory=set)
    training_seeds: set[int] = field(default_factory=set)
    splits: set[str] = field(default_factory=set)
    conditions: set[str] = field(default_factory=set)
    experiments: set[str] = field(default_factory=set)
    episodes: int = 0


@dataclass
class ScenarioRequest:
    path: Path
    seeds: dict[int, SeedRecord] = field(default_factory=dict)

    def record(self, seed: int) -> SeedRecord:
        seed = validate_scenario_seed(seed)
        return self.seeds.setdefault(seed, SeedRecord(seed))


def read_census(path: Path, split: str | None = None) -> dict[int, dict[str, tuple[str, str, bool]]]:
    """A scenario census CSV (``seed,host,os,services,sensitive[,split]``, one
    row per host; ``services`` ``;``-separated) -> seed -> host -> facts."""
    census: dict[int, dict[str, tuple[str, str, bool]]] = defaultdict(dict)
    with path.open(newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        missing = {"seed", "host", "os", "services", "sensitive"} - set(reader.fieldnames or ())
        if missing:
            raise ScenarioFigureError(f"{path} is not a scenario census (missing columns {sorted(missing)})")
        for row in reader:
            if split is not None and row.get("split") not in (None, split):
                continue
            services = ";".join(sorted(s for s in row["services"].split(";") if s))
            census[int(row["seed"])][row["host"]] = (row["os"], services, row["sensitive"].strip().lower() == "true")
    if not census:
        raise ScenarioFigureError(f"no census rows in {path}" + (f" for split {split!r}" if split else ""))
    return dict(census)


def _episode_files(path: Path) -> list[Path]:
    if path.is_file():
        return [path]
    if path.is_dir():
        return sorted(path.rglob("episodes.csv"))
    raise ScenarioFigureError(f"no such episodes file or directory: {path}")


def _recorded_scenario_hash(episodes_csv: Path) -> str | None:
    """The scenario hash ``marla run`` recorded for the run that produced
    ``episodes_csv`` (a run directory, or an evaluation output whose
    ``eval_meta.json`` names its run), if any."""
    folder = episodes_csv.parent
    candidates = [folder / "metadata.json"]
    eval_meta = folder / "eval_meta.json"
    if eval_meta.is_file():
        run_dir = json.loads(eval_meta.read_text(encoding="utf-8")).get("run_dir")
        if run_dir:
            candidates.append(Path(run_dir) / "metadata.json")
    for candidate in candidates:
        if candidate.is_file():
            meta = json.loads(candidate.read_text(encoding="utf-8"))
            recorded = (meta.get("scenario_validation") or {}).get("scenario_hash")
            if recorded:
                return recorded
    return None


def collect_episode_seeds(
    paths: Iterable[Path], requests: dict[str, ScenarioRequest], *, eval_only: bool = False,
    split: str | None = None, only_scenario: ScenarioRealizer | None = None,
) -> dict[str, int]:
    """Adds every (scenario, seed) recorded in MARLA ``episodes.csv`` files to
    ``requests`` (keyed by scenario sha256). Returns counters for the report."""
    stats: Counter = Counter()
    hashes: dict[str, str] = {}
    for path in paths:
        for csv_path in _episode_files(Path(path)):
            recorded_hash = _recorded_scenario_hash(csv_path)
            with csv_path.open(newline="", encoding="utf-8") as fh:
                for row in csv.DictReader(fh):
                    if "seed" not in row or "scenario" not in row:
                        raise ScenarioFigureError(f"{csv_path} has no seed/scenario columns")
                    if eval_only and str(row.get("is_eval", "")).strip().lower() != "true":
                        stats["skipped_not_eval"] += 1
                        continue
                    if split is not None and row.get("split") not in (None, split):
                        stats["skipped_other_split"] += 1
                        continue
                    scenario = Path(row["scenario"])
                    if str(scenario) not in hashes:
                        if not scenario.is_file():
                            raise ScenarioFigureError(f"{csv_path}: recorded scenario {scenario} no longer exists")
                        hashes[str(scenario)] = ScenarioRealizer(scenario).sha256
                    sha = hashes[str(scenario)]
                    if only_scenario is not None and sha != only_scenario.sha256:
                        stats["skipped_other_scenario"] += 1
                        continue
                    if recorded_hash is not None and recorded_hash != sha:
                        raise ScenarioFigureError(
                            f"{csv_path}: scenario {scenario} has changed since the run (recorded sha256 "
                            f"{recorded_hash[:12]}..., file now {sha[:12]}...); refusing to plot a different network"
                        )
                    request = requests.setdefault(sha, ScenarioRequest(only_scenario.path if only_scenario else scenario))
                    rec = request.record(int(row["seed"]))
                    rec.sources.add("episodes")
                    rec.episodes += 1
                    stats["episodes"] += 1
                    if row.get("sensitive_targets_total") not in (None, ""):
                        rec.episode_target_counts.add(int(float(row["sensitive_targets_total"])))
                    if row.get("training_seed") not in (None, ""):
                        rec.training_seeds.add(int(row["training_seed"]))
                    for key, target in (("split", rec.splits), ("condition", rec.conditions), ("experiment", rec.experiments)):
                        if row.get(key):
                            target.add(row[key])
            stats["files"] += 1
    return dict(stats)


def _verify(realization: ScenarioRealization, rec: SeedRecord) -> tuple[dict, str | None]:
    """Checks a reconstruction against what the experiment recorded. Returns
    (verification summary, failure reason or None)."""
    summary: dict = {}
    if rec.census_hosts is not None:
        got = {h.key: (h.os or "", ";".join(sorted(h.services)), h.sensitive) for h in realization.hosts}
        if got != rec.census_hosts:
            diff = sorted(k for k in set(got) | set(rec.census_hosts) if got.get(k) != rec.census_hosts.get(k))
            return summary, f"differs from the census on host(s) {diff}"
        summary["census"] = "match (os, services, sensitivity of every host)"
    if rec.episode_target_counts:
        n = len(realization.sensitive_hosts)
        if rec.episode_target_counts != {n}:
            return summary, f"episodes recorded {sorted(rec.episode_target_counts)} sensitive targets, realization has {n}"
        summary["episodes"] = f"match (sensitive_targets_total = {n} in all {rec.episodes} recorded episodes)"
    if not summary:
        summary["status"] = "not checked against recorded data (reconstructed by the real generator only)"
    return summary, None


# ------------------------------------------------------------------- rendering


@dataclass(frozen=True)
class RenderJob:
    scenario_path: str
    requested_seed: int
    file_name: str
    effective_seed: int
    views: tuple[View, ...]
    formats: tuple[str, ...]
    dpi: int
    size: str | float | None
    caption: bool
    output_dir: str


def _caption(r: ScenarioRealization) -> tuple[str, ...]:
    seed = f"seed {r.realization_seed}"
    if r.regeneration_attempt:
        seed += f" (requested {r.requested_seed}; zero-target regeneration {r.regeneration_attempt})"
    return (f"{r.scenario_name} · {seed} · {len(r.subnets)} subnets, {len(r.hosts)} hosts, "
            f"{len(r.sensitive_hosts)} targets",)


_REALIZERS: dict[str, ScenarioRealizer] = {}


def _realizer(path: str) -> ScenarioRealizer:
    if path not in _REALIZERS:
        _REALIZERS[path] = ScenarioRealizer(path)
    return _REALIZERS[path]


def render_job(job: RenderJob) -> dict:
    """Renders one realization (every requested view and format). Runs in a worker process."""
    realization = _realizer(job.scenario_path).realize(job.requested_seed)
    if realization.realization_seed != job.effective_seed:
        raise ScenarioRealizationError(f"seed {job.requested_seed} no longer realizes effective seed {job.effective_seed}")
    style = ScenarioFigureStyle()
    out = Path(job.output_dir)
    views = {}
    for view in job.views:
        rendered = build_figure(realization, view, size=job.size, caption=_caption(realization) if job.caption else (),
                                style=style)
        stem = out / figure_stem(job.file_name, job.effective_seed, view)
        views[view] = _view_record(rendered, export_figure(rendered, stem, job.formats, job.dpi))
        rendered.figure.clear()
    return {"job": job, "views": views}


# -------------------------------------------------------------------- manifest


def _migrate_v1(manifest: dict) -> dict:
    """Schema 1 held only realizations, with the simplified view named "default"."""
    for entry in manifest["figures"].values():
        entry.setdefault("kind", "realization")
        if "default" in entry.get("views", {}):
            entry["views"] = {"simplified": entry["views"]["default"], **{
                k: v for k, v in entry["views"].items() if k != "default"}}
    manifest["schema"] = MANIFEST_SCHEMA
    return manifest


def load_manifest(output_dir: Path) -> dict:
    path = output_dir / MANIFEST_NAME
    if path.is_file():
        manifest = json.loads(path.read_text(encoding="utf-8"))
        if manifest.get("schema") == "marla.scenario_figures/1":
            manifest = _migrate_v1(manifest)
        if manifest.get("schema") != MANIFEST_SCHEMA:
            raise ScenarioFigureError(f"{path} is not a MARLA scenario-figure manifest (schema {manifest.get('schema')!r})")
        return manifest
    return {"schema": MANIFEST_SCHEMA, "scenarios": {}, "figures": {}, "unreconstructed": []}


def _structure_signature(entry: dict) -> list:
    return [[s["source_index"], s["hosts"], s["targets"]] for s in sorted(entry["subnets"], key=lambda s: s["source_index"])]


def _first_requested(entry: dict) -> int:
    return min(s["requested_seed"] for s in entry["seeds"])


def select_representatives(manifest: dict) -> dict:
    """Marks one ``paper_representative`` figure per scenario (see
    :data:`REPRESENTATIVE_CRITERION`) and returns the selection summary."""
    by_scenario: dict[str, list[dict]] = defaultdict(list)
    for entry in manifest["figures"].values():
        if entry.get("kind") != "realization":
            continue
        entry["paper_representative"] = False
        by_scenario[entry["scenario"]].append(entry)
    selected = {}
    for scenario, entries in sorted(by_scenario.items()):
        counts: Counter = Counter()
        smallest: dict[str, int] = {}
        for e in entries:
            key = json.dumps(_structure_signature(e))
            counts[key] += len(e["seeds"])
            smallest[key] = min(smallest.get(key, _first_requested(e)), _first_requested(e))
        best = min(counts, key=lambda k: (-counts[k], smallest[k]))
        chosen = min((e for e in entries if json.dumps(_structure_signature(e)) == best), key=_first_requested)
        chosen["paper_representative"] = True
        selected[scenario] = {
            "figure": chosen["id"], "effective_seed": chosen["effective_seed"],
            "requested_seed": _first_requested(chosen),
            "signature": {"per_yaml_subnet_[index, hosts, targets]": json.loads(best)},
            "requested_seeds_with_signature": counts[best],
            "requested_seeds_total": sum(counts.values()),
        }
    return {"criterion": REPRESENTATIVE_CRITERION, "selected": selected}


def write_manifest(output_dir: Path, manifest: dict) -> Path:
    figures = dict(sorted(manifest["figures"].items()))
    representative = select_representatives({"figures": figures})
    ordered = {
        "schema": MANIFEST_SCHEMA,
        "description": (
            "MARLA scenario figures: every figure in this directory is one seeded NASimEmu scenario realization, "
            "reconstructed with the real scenario generator (marla.environment.scenario_realization)."
        ),
        "figure_types": FIGURE_TYPES,
        "seed_semantics": SEED_SEMANTICS,
        "ground_truth_note": MANIFEST_GROUND_TRUTH_NOTE,
        "generator": {
            "marla": marla.__version__, "nasimemu": _package_version("nasimemu"),
            "matplotlib": _package_version("matplotlib"), "font_family": ScenarioFigureStyle().font_family,
        },
        "representative_selection": representative,
        "scenarios": dict(sorted(manifest["scenarios"].items())),
        "figures": figures,
        "unreconstructed": sorted(manifest.get("unreconstructed", []), key=lambda u: (u["scenario"], u["requested_seed"])),
    }
    path = output_dir / MANIFEST_NAME
    path.write_text(json.dumps(ordered, indent=2) + "\n", encoding="utf-8")
    manifest.clear()
    manifest.update(ordered)
    return path


# ----------------------------------------------------------------------- batch


@dataclass
class BatchResult:
    rendered: list[str] = field(default_factory=list)
    skipped_existing: list[str] = field(default_factory=list)
    aliases: int = 0
    unreconstructed: list[dict] = field(default_factory=list)
    files_written: Counter = field(default_factory=Counter)
    manifest_path: Path | None = None
    layout_issue_figures: list[str] = field(default_factory=list)


def _file_name_for(manifest: dict, sha256: str, name: str) -> str:
    base = sanitize_name(name)
    for known, info in manifest["scenarios"].items():
        if info["sha256"] == sha256:
            return known
    if base in manifest["scenarios"]:
        return f"{base}_{sha256[:8]}"
    return base


def _register_scenario(manifest: dict, file_name: str, name: str, sha256: str, fmt: str, path: str) -> None:
    info = manifest["scenarios"].setdefault(file_name, {
        "scenario_name": name, "sha256": sha256, "format": fmt, "source_paths": [],
    })
    info["source_paths"] = sorted(set(info["source_paths"]) | {path})


def _refuse_overwrite(paths: list[Path]) -> None:
    if paths:
        shown = "\n  ".join(str(p) for p in paths[:10]) + ("\n  ..." if len(paths) > 10 else "")
        raise ScenarioFigureError(
            f"{len(paths)} figure file(s) already exist:\n  {shown}\n"
            "Use --overwrite to replace them (plot-batch can also --skip-existing to keep them)."
        )


def _view_record(rendered, written: list[Path]) -> dict:
    return {
        "files": {p.suffix[1:]: p.name for p in written},
        "size_in": [round(rendered.width_in, 3), round(rendered.height_in, 3)],
        "scale": round(rendered.scale, 4),
        "min_font_pt": round(rendered.layout.min_font_pt * rendered.scale, 2),
        "layout_issues": check_layout(rendered.layout),
        "edge_crossings": edge_crossings(rendered.layout),
    }


def _definition_caption(d: ScenarioDefinition) -> tuple[str, ...]:
    hosts = d.host_count_range
    host_text = "?" if hosts[0] is None else (f"{hosts[0]}" if hosts[0] == hosts[1] else f"{hosts[0]}–{hosts[1]}")
    return (f"{d.name} · scenario definition · {len(d.subnets)} subnets, {host_text} hosts",)


def plot_definitions(
    paths: Iterable[Path],
    output_dir: Path,
    *,
    views: tuple[View, ...] = VIEWS,
    formats: tuple[str, ...] = FORMATS,
    dpi: int = DEFAULT_DPI,
    size: str | float | None = "natural",
    caption: bool = False,
    overwrite: bool = False,
    skip_existing: bool = False,
    progress: Callable[[str], None] | None = None,
) -> BatchResult:
    """Draws each scenario *definition* (no network is generated) and merges
    ``manifest.json``: ``<scenario>.<fmt>`` and ``<scenario>_verbose.<fmt>``."""
    resolve_width(size)
    say = progress or (lambda _msg: None)
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest = load_manifest(output_dir)
    result = BatchResult()
    definitions = sorted({load_scenario_definition(p).path: load_scenario_definition(p) for p in paths}.values(),
                         key=lambda d: (d.name, d.sha256))
    planned = []
    collisions: list[Path] = []
    for d in definitions:
        file_name = _file_name_for(manifest, d.sha256, d.name)
        _register_scenario(manifest, file_name, d.name, d.sha256, d.format, d.path)
        targets = [output_dir / name for files in figure_files(file_name, None, views, formats).values()
                   for name in files.values()]
        existing = [t for t in targets if t.exists()]
        if existing and skip_existing and len(existing) == len(targets):
            result.skipped_existing.append(file_name)
            continue
        if existing and not overwrite and not skip_existing:
            collisions.extend(existing)
        planned.append((d, file_name))
    _refuse_overwrite(collisions)
    style = ScenarioFigureStyle()
    for d, file_name in planned:
        entry = manifest["figures"].get(file_name) or {"id": file_name, "kind": "definition", "views": {}}
        entry.update({
            "kind": "definition", "scenario": file_name, "scenario_name": d.name, "scenario_path": d.path,
            "scenario_sha256": d.sha256, "n_subnets": len(d.subnets),
            "hosts_min": d.host_count_range[0], "hosts_max": d.host_count_range[1],
            "targets_min": d.targets_min, "targets_max": d.targets_max, "p_zero_targets": d.p_zero_targets,
            "subnets": d.to_dict()["subnets"], "warnings": list(d.warnings),
        })
        for view in views:
            rendered = build_figure(d, view, size=size, caption=_definition_caption(d) if caption else (), style=style)
            written = export_figure(rendered, output_dir / figure_stem(file_name, None, view), formats, dpi)
            entry["views"][view] = _view_record(rendered, written)
            result.files_written.update(p.suffix[1:] for p in written)
            if entry["views"][view]["layout_issues"]:
                result.layout_issue_figures.append(file_name)
            rendered.figure.clear()
        entry.update({"formats": sorted(set(entry.get("formats", [])) | set(formats), key=FORMATS.index),
                      "dpi": dpi, "size": size if size is not None else "natural", "caption": caption})
        manifest["figures"][file_name] = entry
        result.rendered.append(file_name)
        say(f"{file_name}: definition ({', '.join(views)})")
    result.manifest_path = write_manifest(output_dir, manifest)
    return result


def plot_requests(
    requests: dict[str, ScenarioRequest],
    output_dir: Path,
    *,
    views: tuple[View, ...] = VIEWS,
    formats: tuple[str, ...] = FORMATS,
    dpi: int = DEFAULT_DPI,
    size: str | float | None = "natural",
    caption: bool = False,
    deduplicate: bool = True,
    overwrite: bool = False,
    skip_existing: bool = False,
    jobs: int = 1,
    progress: Callable[[str], None] | None = None,
) -> BatchResult:
    """Reconstructs, verifies, deduplicates and renders every requested
    realization into ``output_dir`` and merges ``manifest.json``."""
    for view in views:
        if view not in VIEWS:
            raise ScenarioFigureError(f"unknown view {view!r}")
    resolve_width(size)
    if overwrite and skip_existing:
        raise ScenarioFigureError("--overwrite and --skip-existing are mutually exclusive")
    say = progress or (lambda _msg: None)
    output_dir.mkdir(parents=True, exist_ok=True)
    manifest = load_manifest(output_dir)
    result = BatchResult()

    # 1. reconstruct and verify every requested seed (cheap; no rendering yet)
    planned: list[tuple[dict, RenderJob]] = []
    for sha, request in sorted(requests.items(), key=lambda kv: (scenario_display_name(kv[1].path), kv[0])):
        realizer = ScenarioRealizer(request.path)
        if realizer.sha256 != sha:
            raise ScenarioFigureError(f"{request.path} changed while plotting")
        file_name = _file_name_for(manifest, realizer.sha256, realizer.name)
        _register_scenario(manifest, file_name, realizer.name, realizer.sha256, realizer.format, str(realizer.path))
        say(f"{file_name}: reconstructing {len(request.seeds)} seed(s)")
        groups: dict[str, list[tuple[ScenarioRealization, SeedRecord, dict]]] = defaultdict(list)
        for seed in sorted(request.seeds):
            rec = request.seeds[seed]
            try:
                realization = realizer.realize(seed)
            except (ScenarioRealizationError, ValueError) as exc:
                result.unreconstructed.append({"scenario": file_name, "requested_seed": seed, "reason": str(exc)})
                continue
            verification, failure = _verify(realization, rec)
            if failure:
                result.unreconstructed.append({"scenario": file_name, "requested_seed": seed, "reason": failure})
                continue
            key = realization.realization_fingerprint if deduplicate else f"{realization.realization_seed}"
            groups[key].append((realization, rec, verification))

        existing = {e["realization_fingerprint"]: e for e in manifest["figures"].values()
                    if e["scenario"] == file_name and e.get("kind") == "realization"}
        for members in groups.values():
            members.sort(key=lambda m: (m[0].realization_seed, m[0].requested_seed))
            canonical = members[0][0]
            prior = existing.get(canonical.realization_fingerprint) if deduplicate else None
            effective = prior["effective_seed"] if prior else canonical.realization_seed
            fig_id = figure_stem(file_name, effective, "simplified")
            entry = manifest["figures"].get(fig_id) or {
                "id": fig_id, "kind": "realization", "scenario": file_name, "scenario_name": realizer.name,
                "scenario_path": str(realizer.path), "scenario_sha256": realizer.sha256,
                "effective_seed": effective, "seeds": [], "views": {}, "warnings": [],
            }
            if entry.get("realization_fingerprint") not in (None, canonical.realization_fingerprint):
                raise ScenarioFigureError(f"{fig_id} in the manifest describes a different realization")
            entry.update({
                "realization_fingerprint": canonical.realization_fingerprint,
                "topology_fingerprint": canonical.topology_fingerprint,
                "n_subnets": len(canonical.subnets), "n_hosts": len(canonical.hosts),
                "n_targets": len(canonical.sensitive_hosts),
                "subnets": [
                    {"source_index": s.source_index, "subnet_id": s.subnet_id, "label": s.label, "hosts": s.size,
                     "targets": sum(h.sensitive for h in canonical.hosts_in(s.subnet_id)),
                     "internet_facing": s.internet_facing}
                    for s in canonical.subnets
                ],
                "subnet_permutation": list(canonical.subnet_permutation),
                "targets": [h.key for h in canonical.sensitive_hosts],
            })
            entry["warnings"] = sorted(set(entry["warnings"]) | set(canonical.warnings))
            seeds = {s["requested_seed"]: s for s in entry["seeds"]}
            for realization, rec, verification in members:
                seeds[realization.requested_seed] = {
                    "requested_seed": realization.requested_seed,
                    "realization_seed": realization.realization_seed,
                    "regeneration_attempt": realization.regeneration_attempt,
                    "verification": verification,
                    "provenance": {
                        "sources": sorted(rec.sources), "episodes": rec.episodes,
                        "training_seeds": sorted(rec.training_seeds), "splits": sorted(rec.splits),
                        "conditions": sorted(rec.conditions), "experiments": sorted(rec.experiments),
                    },
                }
            entry["seeds"] = [seeds[k] for k in sorted(seeds)]
            if any(s["realization_seed"] != effective for s in entry["seeds"]):
                entry["note"] = ("some requested seeds generate this network through a different effective seed "
                                 "(zero-target regeneration or an identical realization); see seeds[]")
            manifest["figures"][fig_id] = entry
            result.aliases += len(members) - 1
            job = RenderJob(str(realizer.path), canonical.requested_seed if not prior else _seed_for(entry, effective),
                            file_name, effective, views, formats, dpi, size, caption, str(output_dir))
            planned.append((entry, job))
        # Keep earlier failures of seeds this batch did not retry; replace the rest.
        manifest["unreconstructed"] = [
            u for u in manifest.get("unreconstructed", [])
            if not (u["scenario"] == file_name and u["requested_seed"] in request.seeds)
        ] + [u for u in result.unreconstructed if u["scenario"] == file_name]

    # 2. overwrite policy, before anything is written
    to_render: list[tuple[dict, RenderJob]] = []
    collisions: list[Path] = []
    for entry, job in planned:
        targets = [output_dir / name for files in figure_files(job.file_name, job.effective_seed, views, formats).values()
                   for name in files.values()]
        existing_files = [t for t in targets if t.exists()]
        if existing_files and skip_existing and len(existing_files) == len(targets):
            result.skipped_existing.append(entry["id"])
            continue
        if existing_files and not overwrite and not skip_existing:
            collisions.extend(existing_files)
        to_render.append((entry, job))
    _refuse_overwrite(collisions)

    # 3. render (optionally in parallel; every job is independent and deterministic)
    entries = {job: entry for entry, job in to_render}
    jobs_list = [job for _, job in to_render]
    total = len(jobs_list)

    def finished(done: int, outcome: dict) -> None:
        job = outcome["job"]
        entry = entries[job]
        entry["views"].update(outcome["views"])
        entry["formats"] = sorted(set(entry.get("formats", [])) | set(job.formats), key=FORMATS.index)
        entry["dpi"] = job.dpi
        entry["size"] = job.size if job.size is not None else "natural"
        entry["caption"] = job.caption
        result.rendered.append(entry["id"])
        for view in outcome["views"].values():
            result.files_written.update(name.rsplit(".", 1)[1] for name in view["files"].values())
            if view["layout_issues"]:
                result.layout_issue_figures.append(entry["id"])
        say(f"[{done}/{total}] {entry['id']}")

    if jobs <= 1 or total <= 1:
        for i, job in enumerate(jobs_list, start=1):
            finished(i, render_job(job))
    else:
        with ProcessPoolExecutor(max_workers=jobs, mp_context=get_context("spawn")) as pool:
            for i, outcome in enumerate(pool.map(render_job, jobs_list, chunksize=4), start=1):
                finished(i, outcome)

    result.manifest_path = write_manifest(output_dir, manifest)
    return result


def _seed_for(entry: dict, effective: int) -> int:
    """A requested seed known to reproduce ``effective`` (for re-rendering an existing figure)."""
    for s in entry["seeds"]:
        if s["realization_seed"] == effective:
            return s["requested_seed"]
    return effective
